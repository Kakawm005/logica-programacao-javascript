//12) Escreva um algoritmo para ler uma temperatura em graus Fahrenheit, calcular e escrever o valor 
//correspondente em graus Celsius

let ceusius = parseFloat(prompt("Digite os graus em Ceusius e farei a conversão para Fahrenheit: "))

let fahrenheit = (ceusius * 9/5) + 32

alert(`ceusius: ${ceusius} = ${fahrenheit} :Fahrenheit`)