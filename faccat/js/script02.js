//6) Escreva um algoritmo para ler as dimensões de um retângulo (base e altura), calcular e escrever a 
//área do retângulo.

base = parseFloat(prompt("Digite a base de um retângulo: "))

altura = parseFloat(prompt("Digite a altura de um retângulo: ")) 

area = base * altura

alert(`A base do retângulo é: ${area}`)